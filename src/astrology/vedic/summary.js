/** Exact-match strings that always mean a genuinely deferred/unbuilt feature - see module doc comment "UNRESOLVED CONVENTIONS" for the full audit trail on each. */
const UNRESOLVED_EXACT_VALUES = new Set(["not_implemented", "not_yet_implemented", "not_yet_evaluated", "deferred"]);
/** Prefixes that also mean "unresolved" for a more specific future value in either family, without a bare substring match on "not". */
const UNRESOLVED_PREFIXES = ["not_implemented_", "deferred_"];
/** Exact-match strings that are a PERMANENT, deliberate policy/architecture outcome - never a deferred feature, even though each happens to contain "not". Individually named, never pattern-matched. */
const INTENTIONAL_NOT_APPLICABLE_EXACT_VALUES = new Set(["none", "not_applicable", "not_assigned_due_to_traditional_variance"]);

/**
 * Classifies one `chart.vedic.meta` (or this module's own) status string
 * into exactly one of three explicit, documented outcomes - see the
 * module doc comment "UNRESOLVED CONVENTIONS" for the full rationale and
 * pre-lock audit. Deterministic and explainable: no broad substring
 * match on words like "not".
 * @param {string} value
 * @returns {"unresolved"|"intentional_not_applicable"|"implemented"}
 */
export function classifyImplementationStatus(value) {
  if (INTENTIONAL_NOT_APPLICABLE_EXACT_VALUES.has(value)) return "intentional_not_applicable";
  if (UNRESOLVED_EXACT_VALUES.has(value)) return "unresolved";
  if (UNRESOLVED_PREFIXES.some((prefix) => value.startsWith(prefix))) return "unresolved";
  return "implemented";
}

/** camelCase meta key -> snake_case topic label, e.g. "functionalBenefic" -> "functional_benefic". Never a hand-curated topic list (Part L). */
function topicFromMetaKey(key) {
  return key.replace(/([A-Z])/g, "_$1").toLowerCase();
}

function scanForUnresolved(obj, source) {
  const found = [];
  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === "string" && classifyImplementationStatus(value) === "unresolved") {
      found.push({ topic: topicFromMetaKey(key), metaKey: key, status: value, source });
    }
  }
  return found;
}

function buildUnresolvedConventions(vedicMeta) {
  return [
    ...scanForUnresolved(vedicMeta, "chart.vedic.meta"),
    ...scanForUnresolved(
      { dispositorLoopOrderedPath: DISPOSITOR_LOOP_ORDERED_PATH_STATUS },
      "chart.vedic.summary.lordship.dispositorNetwork",
    ),
  ];
}

