/**
 * Vedic Technical Summary & Evidence Layer — Phase 4F.
 *
 * THIS IS AN AGGREGATION / NORMALIZATION LAYER ONLY. It performs ZERO new
 * astronomical calculation, ZERO new sidereal/Bhava/Nakshatra/dignity
 * computation, and creates NO new Jyotish doctrine. Every field below is
 * read (and, where noted, regrouped/relabeled for traceability) from an
 * already-computed, already-locked upstream result: Phase 4A (sidereal
 * Lagna/Navagraha position), Phase 4B (Whole-Sign Bhava structure and
 * house ownership), Phase 4C (Nakshatra/Pada), Phase 4D (dignity and
 * technical condition), and Phase 4E (dispositor chains, loops, and
 * lordship structure).
 *
 * Phase 4A-4E calculate technical evidence. Phase 4F organizes that
 * evidence for inspection/export. It does not reinterpret it:
 *
 *   - NO Vimshottari Dasha, Navamsa/Varga, Shadbala, Ashtakavarga,
 *     Drishti, or Yoga detection of any kind.
 *   - NO functional benefic/malefic, Yogakaraka, Maraka, or Badhaka.
 *   - NO temporary/compound friendship, no Avastha.
 *   - NO score of any kind (grahaScore, bhavaScore, strengthScore, ...).
 *   - NO interpretive label ("strong", "weak", "auspicious",
 *     "inauspicious", career/relationship/wealth semantics, or any
 *     narrative text).
 *
 * REUSE, NEVER REBUILD: this module takes the already-built `grahas`
 * (Phase 4A), `bhava` (Phase 4B), `nakshatra` (Phase 4C), `condition`
 * (Phase 4D), and `lordship` (Phase 4E) objects, plus the assembled
 * `chart.vedic.meta`, as read-only input. It never mutates any of them,
 * and the value it returns is deep-cloned (`structuredClone`) before
 * being handed back, so mutating `chart.vedic.summary` afterward can
 * never corrupt any locked Phase 4A-4E source structure.
 *
 * RAHU/KETU: only evidence actually supported by Phase 4A-4E is
 * included. Dignity, house ownership, and multi-step dispositor chains
 * are never fabricated for the lunar nodes — those sections carry an
 * explicit `applicable: false` rather than an invented value, mirroring
 * exactly how Phase 4D/4E already treat the nodes.
 *
 * DISPOSITOR LOOP ORDERED PATH (Part I): Phase 4E's public output
 * canonicalizes a loop's membership by alphabetically sorting display
 * names for deduplication (`lordship.js`'s `canonicalizeLoop`) — the
 * actual DIRECTIONAL cycle order that produced that loop is not
 * preserved in Phase 4E's returned structure. Rather than reconstructing
 * or inferring that order here (which would mean this aggregation layer
 * quietly re-deriving a fact Phase 4E itself does not expose), this
 * module preserves the canonical membership set verbatim
 * (`canonicalMembers`) and explicitly reports `orderedPath: null`,
 * recorded as its own `"not_implemented"` marker
 * (`DISPOSITOR_LOOP_ORDERED_PATH_STATUS`) so it surfaces automatically
 * in `unresolvedConventions` rather than being silently absent.
 *
 * UNRESOLVED CONVENTIONS (Part L): generated by scanning the LIVE
 * `chart.vedic.meta` values (plus this module's own
 * `DISPOSITOR_LOOP_ORDERED_PATH_STATUS`) through an explicit, documented
 * classifier (`classifyImplementationStatus`) — never a hard-coded topic
 * list, and never a broad substring match on a word like `"not"` (several
 * INTENTIONAL, permanent policy outcomes also happen to contain "not" —
 * see below). A topic disappears from this list on its own the moment a
 * future phase resolves it (i.e. its meta value stops classifying as
 * `"unresolved"`).
 *
 * PRE-LOCK AUDIT (see README §24.1 for the full trail): the original
 * detector recognized exactly three literal strings
 * (`"not_implemented"`/`"not_yet_implemented"`/`"deferred"`) via a plain
 * `Set.has()` equality check. Auditing the complete live
 * `chart.vedic.meta` inventory against the three explicit categories
 * below confirmed the equality check had zero false positives and zero
 * false negatives for TODAY's metadata (every genuinely-deferred field in
 * this project has always used the single literal `"not_implemented"`),
 * but the policy itself was under-specified: it had no documented,
 * deterministic answer for a future value shaped like
 * `"not_implemented_pending_research"` or `"deferred_due_to_..."`
 * (Phase 3H's own classical marker vocabulary already uses that second
 * shape), and it relied on an unexplained implicit exclusion of `"none"`
 * rather than a named category. `classifyImplementationStatus` below
 * replaces the bare equality check with three explicit, named outcomes:
 *
 *   - `"unresolved"`: a genuinely deferred/unbuilt technical feature a
 *     future phase could implement. Recognized: the exact literal this
 *     project has used everywhere since Phase 4B (`"not_implemented"`),
 *     the generic forms the Phase 4F brief itself named
 *     (`"not_yet_implemented"`, `"not_yet_evaluated"` — the latter
 *     already established Phase 3H vocabulary, reused here for
 *     cross-project consistency — and exact `"deferred"`), and two
 *     PREFIXES (`"not_implemented_"`, `"deferred_"`) so a more specific
 *     future value in either family is still recognized without a bare
 *     substring match on "not".
 *   - `"intentional_not_applicable"`: a PERMANENT, deliberate policy
 *     outcome that happens to contain "not" but is never a deferred
 *     feature — `"none"` (this project's own explicit "we do not
 *     interpret, ever" marker, e.g. `vedicInterpretation: "none"`),
 *     `"not_applicable"`, and `"not_assigned_due_to_traditional_variance"`
 *     (Rahu/Ketu dignity — individually named, not pattern-matched: this
 *     project's own research, documented in `dignityTables.js`/
 *     `condition.js`, established that own-sign/exaltation/Moolatrikona
 *     are genuinely disputed across Jyotish schools for the lunar nodes,
 *     so this is a permanent selected policy, not "not built yet").
 *   - `"implemented"`: everything else — an actual chosen convention name
 *     (e.g. `"bphs_critical_edition"`) or descriptive fact. This also
 *     covers `externalVerification: "swiss_ephemeris_dev_only_not_production"`
 *     — a note about the DEV-ONLY VERIFICATION TOOLING'S deployment scope,
 *     not a Jyotish feature awaiting implementation, so it is classified
 *     `"implemented"` (a settled, permanent statement) rather than
 *     pattern-matched into `"unresolved"` off the word "not".
 *
 * The audit reran the full live inventory under this explicit policy and
 * confirmed the resulting topic list is IDENTICAL to the prior one (13
 * topics) for the locked verification chart — the refactor changes the
 * classification's explicitness and future robustness, not today's
 * output. See README §24.1 for the complete inventory and reasoning.
 */

