function buildGrahaEvidenceMap(sources) {
  const grahasEvidence = {};
  for (const key of CLASSICAL_GRAHA_KEYS) {
    grahasEvidence[key] = buildClassicalGrahaEvidence(key, sources);
  }
  for (const key of NODE_KEYS) {
    grahasEvidence[key] = buildNodeGrahaEvidence(key, sources);
  }
  return grahasEvidence;
}

/** 12 normalized Bhava evidence records (Part F), built primarily from Phase 4E's own `houseLordMatrix` (which already combines Phase 4B's placement facts with Phase 4D's dignity/retrograde/combustion evidence for that Bhava's lord) plus Phase 4B's own `houses` for occupant Grahas and Phase 4E's own `houseGroups` for membership. */
function buildBhavaEvidence({ bhava, condition, lordship }) {
  return lordship.houseLordMatrix.map((row) => {
    const house = bhava.houses[row.sourceBhava - 1];
    const lordKey = KEY_BY_DISPLAY_NAME[row.lord];
    return {
      bhavaNumber: row.sourceBhava,
      rashi: row.sourceRashi,
      lord: row.lord,
      grahas: [...house.grahas],
      lordPlacement: { lordRashi: row.lordRashi, lordBhava: row.lordBhava },
      lordCondition: {
        dignityLabels: [...condition.planets[lordKey].dignity.dignityLabels],
        rashiDignityStatus: row.lordDignityStatus,
        retrograde: row.lordIsRetrograde,
        combustion: row.lordIsCombust,
      },
      houseGroups: {
        isKendra: lordship.houseGroups.kendra.includes(row.sourceBhava),
        isTrikona: lordship.houseGroups.trikona.includes(row.sourceBhava),
        isDusthana: lordship.houseGroups.dusthana.includes(row.sourceBhava),
        isUpachaya: lordship.houseGroups.upachaya.includes(row.sourceBhava),
      },
      provenance: { rashiAndLord: PROVENANCE.BHAVA, lordCondition: PROVENANCE.DIGNITY_CONDITION, houseGroups: PROVENANCE.LORDSHIP_DISPOSITOR },
    };
  });
}

